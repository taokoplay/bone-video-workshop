import argparse,json
from pathlib import Path
from playwright.sync_api import sync_playwright,expect
parser=argparse.ArgumentParser()
parser.add_argument('fixture',type=Path)
parser.add_argument('--screenshot',type=Path)
args=parser.parse_args()
checks=[]
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,channel='chrome')
    page=browser.new_page(viewport={'width':1440,'height':1000})
    errors=[]; page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(args.fixture.resolve().as_uri(),wait_until='networkidle')
    page.get_by_role('button',name='项目',exact=True).click()
    assets=page.evaluate('window.__fixture.snapshot.document.assets')
    character=next(a for a in assets if a.get('type')=='角色')
    trigger=page.get_by_role('button',name=f"查看{character['name']}详情",exact=True)
    assert character['description'] not in page.locator('.asset-grid').inner_text()
    assert page.locator('.bw-asset-intro,.bw-asset-details').count()==0
    trigger.locator('.asset-card-preview').click()
    dialog=page.get_by_role('dialog',name=character['name'],exact=True)
    expect(dialog).to_be_visible()
    for key in ['description','profile','imagePrompt','negativePrompt']:
        assert character[key] in dialog.inner_text()
    dialog.get_by_role('button',name='复制提示词',exact=True).click()
    copied=page.evaluate('window.__lastCopy')
    assert character['imagePrompt'] in copied and character['negativePrompt'] in copied
    dialog.get_by_role('button',name='复制完善指令',exact=True).click()
    assert character['id'] in page.evaluate('window.__lastCopy') and 'update_asset' in page.evaluate('window.__lastCopy')
    dialog.get_by_role('button',name='关闭资产详情').click()
    expect(dialog).not_to_be_visible(); expect(trigger).to_be_focused()
    checks.append('Compact cards hide descriptions; image click opens all details and copy actions work')
    trigger.press('Enter')
    expect(dialog.get_by_role('button',name='关闭资产详情')).to_be_focused()
    for _ in range(6):
        page.keyboard.press('Tab')
        assert dialog.evaluate('d=>d.contains(document.activeElement)')
    page.keyboard.press('Escape')
    expect(dialog).not_to_be_visible(); expect(trigger).to_be_focused()
    trigger.locator('strong').click()
    expect(dialog).to_be_visible()
    page.mouse.click(2,2)
    expect(dialog).not_to_be_visible(); expect(trigger).to_be_focused()
    checks.append('Name and keyboard activation, modal focus, Escape, backdrop and focus return work')
    image_asset=next(a for a in assets if a.get('mediaId') and a['type']!='声音')
    page.get_by_role('button',name=f"查看{image_asset['name']}详情",exact=True).click()
    image_dialog=page.get_by_role('dialog',name=image_asset['name'],exact=True)
    expect(image_dialog.locator('.bw-asset-dialog-preview img')).to_be_visible()
    image_dialog.locator('img').evaluate('(e)=>e.decode()')
    assert image_dialog.locator('img').evaluate('e=>e.naturalWidth>0')
    image_dialog.get_by_role('button',name='关闭资产详情').click()
    checks.append('Adopted image decodes inside asset detail dialog')
    legacy=page.locator('.bw-legacy-characters')
    original=page.evaluate('window.__fixture.snapshot.document.projectBible.characters')
    legacy_trigger=legacy.get_by_role('button',name='查看待归档人物资料',exact=True)
    legacy_dialog=page.get_by_role('dialog',name='待归档人物资料（旧版项目设定）',exact=True)
    assert original not in page.locator('body').inner_text()
    assert legacy.locator('summary').count()==0
    legacy_trigger.focus(); legacy_trigger.press('Enter')
    expect(legacy_dialog.locator('.bw-asset-text')).to_have_text(original)
    expect(legacy_dialog.get_by_role('button',name='关闭人物资料')).to_be_focused()
    for _ in range(4):
        page.keyboard.press('Tab')
        assert legacy_dialog.evaluate('d=>d.contains(document.activeElement)')
    legacy_dialog.get_by_role('button',name='复制归档指令').click()
    assert '全部归档成功' in page.evaluate('window.__lastCopy')
    page.keyboard.press('Escape')
    expect(legacy_dialog).not_to_be_visible(); expect(legacy_trigger).to_be_focused()
    legacy_trigger.click(); page.mouse.click(2,2)
    expect(legacy_dialog).not_to_be_visible(); expect(legacy_trigger).to_be_focused()
    legacy_trigger.click(); legacy_dialog.get_by_role('button',name='关闭人物资料').click()
    expect(legacy_dialog).not_to_be_visible()
    assert page.evaluate('window.__fixture.snapshot.document.projectBible.characters')==original
    checks.append('Legacy text is hidden until modal opens; exact text, copy, keyboard and all close paths work without mutation')
    search=page.locator('.asset-search input'); search.fill('承担现在')
    expect(page.locator('.asset-card')).to_have_count(1)
    expect(page.locator('.asset-card-open strong')).to_have_text(character['name'])
    search.fill('')
    page.evaluate("window.__fixture.snapshot.document.assets.find(a=>a.type==='角色').profile='<img src=x onerror=window.__xss=1>\\n'+('人物设定。'.repeat(3000))")
    page.get_by_role('button',name='刷新',exact=True).click()
    trigger.click()
    assert '<img src=x onerror=window.__xss=1>' in dialog.inner_text()
    assert not page.evaluate('Boolean(window.__xss)')
    assert dialog.locator('.bw-asset-dialog-body').evaluate('e=>e.scrollHeight>e.clientHeight')
    checks.append('Search and refreshed long text work; dialog body scrolls and text is not executed')
    for width in [1440,900,600,390]:
        page.set_viewport_size({'width':width,'height':1000})
        for theme in ['dark','light']:
            page.evaluate('(t)=>document.documentElement.dataset.theme=t',theme)
            assert page.evaluate('document.documentElement.scrollWidth<=innerWidth'),(width,theme)
            assert dialog.evaluate('e=>{const r=e.getBoundingClientRect();return r.left>=0&&r.top>=0&&r.right<=innerWidth&&r.bottom<=innerHeight&&e.scrollWidth<=e.clientWidth}'),(width,theme)
            expect(dialog.get_by_role('button',name='关闭资产详情')).to_be_in_viewport()
        checks.append(f'{width}px dialog and close control fit both themes')
    # Exercise render cleanup via the same application tab path; normal pointer
    # input cannot reach the inert background while the dialog is open.
    page.evaluate("[...document.querySelectorAll('#tabs button')].find(b=>b.textContent==='剧本').click()")
    assert page.locator('dialog[open]').count()==0
    page.get_by_role('button',name='项目',exact=True).click()
    checks.append('View changes remove the active dialog without a lingering backdrop')
    audio_id=page.evaluate("Object.entries(window.__media).find(([id,m])=>m.kind==='audio')[0]")
    page.evaluate("id=>window.__fixture.snapshot.document.assets=[{id:'sound',name:'风声',type:'声音',imagePrompt:'风穿过铁轨',mediaId:id},{id:'old',name:'旧道具',type:'道具',description:'Existing intro'}]",audio_id)
    page.get_by_role('button',name='刷新',exact=True).click()
    assert page.locator('.asset-card-open audio').count()==0
    sound_trigger=page.get_by_role('button',name='查看风声详情',exact=True)
    sound_trigger.click()
    sound=page.get_by_role('dialog',name='风声',exact=True)
    assert '制作提示词' in sound.inner_text() and '生图提示词' not in sound.inner_text()
    page.wait_for_function("document.querySelector('.bw-asset-dialog[open] audio')?.readyState>=2")
    sound.get_by_role('button',name='播放',exact=False).click()
    page.wait_for_function("document.querySelector('.bw-asset-dialog[open] audio')?.currentTime>0.1")
    page.evaluate("window.__dialogAudio=document.querySelector('.bw-asset-dialog[open] audio')")
    page.keyboard.press('Escape')
    expect(sound).not_to_be_visible()
    page.wait_for_function('window.__dialogAudio.paused')
    sound_trigger.click()
    expect(sound.locator('audio')).to_have_count(1)
    sound.get_by_role('button',name='关闭资产详情').click()
    checks.append('Audio loads in dialog, plays, stops on close and reopens without duplicate players')
    page.get_by_role('button',name='查看旧道具详情',exact=True).click()
    old=page.get_by_role('dialog',name='旧道具',exact=True)
    expect(old).to_contain_text('尚未填写提示词')
    old.get_by_role('button',name='关闭资产详情').click()
    page.evaluate("window.__fixture.snapshot.document.assets=[]")
    page.get_by_role('button',name='刷新',exact=True).click()
    expect(page.locator('.bw-legacy-characters')).to_be_visible()
    legacy_trigger.click()
    expect(legacy_dialog.locator('.bw-asset-text')).to_have_text(original)
    legacy_dialog.get_by_role('button',name='关闭人物资料').click()
    page.evaluate("window.__fixture.snapshot.document.projectBible.characters='<img src=x onerror=window.__legacyXss=1>\\n'+('旧人物资料。'.repeat(2500))")
    page.get_by_role('button',name='刷新',exact=True).click()
    legacy_trigger.click()
    assert not page.evaluate('Boolean(window.__legacyXss)')
    assert legacy_dialog.locator('img').count()==0
    assert legacy_dialog.locator('.bw-asset-text').inner_text()==page.evaluate('window.__fixture.snapshot.document.projectBible.characters')
    for width in [1440,900,600,390]:
        page.set_viewport_size({'width':width,'height':1000})
        for theme in ['dark','light']:
            page.evaluate('(t)=>document.documentElement.dataset.theme=t',theme)
            assert legacy_dialog.evaluate('e=>{const r=e.getBoundingClientRect();return r.left>=0&&r.top>=0&&r.right<=innerWidth&&r.bottom<=innerHeight&&e.scrollWidth<=e.clientWidth}')
            assert legacy_dialog.locator('.bw-legacy-dialog-body').evaluate('e=>e.scrollHeight>e.clientHeight')
            expect(legacy_dialog.get_by_role('button',name='关闭人物资料')).to_be_in_viewport()
    page.evaluate("[...document.querySelectorAll('#tabs button')].find(b=>b.textContent==='剧本').click()")
    assert page.locator('dialog[open]').count()==0
    page.get_by_role('button',name='项目',exact=True).click()
    page.evaluate("window.__fixture.snapshot.document.projectBible.characters=''")
    page.get_by_role('button',name='刷新',exact=True).click()
    expect(page.locator('.bw-legacy-characters')).to_have_count(0)
    checks.append('Legacy-only work supports modal; long text is safe and responsive; view changes clean up and empty data removes entry')
    assert not errors,errors
    if args.screenshot:
        page.reload(wait_until='networkidle')
        page.set_viewport_size({'width':1440,'height':1000})
        page.get_by_role('button',name='项目',exact=True).click()
        page.evaluate("document.documentElement.dataset.theme='dark'")
        page.get_by_role('button',name=f"查看{character['name']}详情",exact=True).click()
        page.screenshot(path=str(args.screenshot))
    browser.close()
print(json.dumps({'passed':len(checks),'checks':checks},ensure_ascii=False,indent=2))
